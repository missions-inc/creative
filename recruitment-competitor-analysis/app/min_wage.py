def fallback_min_wage(prefecture: str) -> int | None:
    """都道府県名からフォールバック最低賃金を返す（「東京」「東京都」どちらでも可）"""
    if prefecture in MIN_WAGE_FALLBACK:
        return MIN_WAGE_FALLBACK[prefecture]
    for name, wage in MIN_WAGE_FALLBACK.items():
        if name.rstrip("都道府県") == prefecture.rstrip("都道府県"):
            return wage
    return None
